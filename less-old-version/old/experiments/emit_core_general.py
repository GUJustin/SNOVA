#!/usr/bin/env python3
"""Emit determined solving-degree cores for ANY square q=19 SNOVA shape
FROM THE OFFICIAL C-reference KAT key.

The shipped `kat_public_key` is hardcoded to Level-I l=4. Here we generalize it
to arbitrary square (l=r) shapes (the only change needed is using official_S(p.l)
instead of official_S(4)), and we VERIFY the reconstruction byte-for-byte against
the KAT's packed public key generated by the SNOVA C reference. Then the residual
system is built by the same parametric pipeline used for Level-I, and the emitted
polynomials are verified against the reference verifier direct_output on random
points (exact over F_19) before anything is written.

Square specialization: fix (residual_vars - core_n) residual coordinates to their
planted values.  For l=4 shapes this reproduces the paper's attack core (the
estimator selects square-specialization there).  For l=2 shapes the paper uses a
Hashimoto change-of-basis reduction that this tool does NOT reproduce; the l=2
core emitted here is the valid-but-not-gate-optimal square-specialization
alternative, tagged 'supplementary' and run only as a structural cross-check.
"""
from __future__ import annotations
