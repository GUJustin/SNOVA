from pathlib import Path
import numpy as np

Q = 19
ROOT = Path(__file__).resolve().parents[1]
REPRO = ROOT/'files'/'SNOVA_Symmetry_Quotient_Reproducibility_2026-07-19'/'repro'
SNAP = ROOT/'files'/'SNOVA_Symmetry_Quotient_Reproducibility_2026-07-19'/'source_snapshots'
sys.path.insert(0, str(REPRO)); sys.path.insert(0, str(ROOT/'experiments'))
import symmetry_attack_validation as V   # noqa: E402
import emit_level1_core as EM            # noqa: E402

# Square q=19 shapes. core_n is the number of variables kept after coordinate
# specialization (fix residual_vars - core_n coords to their planted values).
#
#  - l=4 shapes: the estimator's own cost model selects square-specialization, so
#    this coordinate-fix core IS the paper's attack core.  kind='paper-core'.
#  - l=2 shapes: the estimator selects Hashimoto, whose dominant determined block
#    (hashimoto field below) is produced by a LINEAR CHANGE OF BASIS, not a
#    coordinate fix, and is not emitted by the shipped repro package.  The core we
#    emit here is instead the VALID-BUT-NOT-GATE-OPTIMAL square-specialization
#    alternative for the same official key -- a genuine determined subsystem, run
#    only as a structural cross-check (semi-regular vs. exploitable structure),
#    NOT as the paper's l=2 gate-cost core.  kind='supplementary'.
SHAPES = {
    'I_l4':   dict(idx=0, kat='PQCsignKAT_SNOVA_28_5_19_4.txt',  core_n=41, kind='paper-core'),
    'III_l4': dict(idx=3, kat='PQCsignKAT_SNOVA_40_7_19_4.rsp',  core_n=55, kind='paper-core'),
    'V_l4':   dict(idx=6, kat='PQCsignKAT_SNOVA_50_9_19_4.rsp',  core_n=73, kind='paper-core'),
    'I_l2':   dict(idx=1, kat='PQCsignKAT_SNOVA_48_16_19_2.rsp', core_n=36, kind='supplementary',
                   hashimoto='dominant block 46/35 (a=2,k=11); paper l=2 gate-cost core'),
    'III_l2': dict(idx=4, kat='PQCsignKAT_SNOVA_72_24_19_2.rsp', core_n=60, kind='supplementary',
                   hashimoto='dominant block 70/55 (a=2,k=15); paper l=2 gate-cost core'),
    'V_l2':   dict(idx=7, kat='PQCsignKAT_SNOVA_96_32_19_2.rsp', core_n=79, kind='supplementary',
                   hashimoto='dominant block 94/71 (a=2,k=23); paper l=2 gate-cost core'),
}


def kat_public_key_general(seed48: bytes, p):
    """V.kat_public_key generalized to square shapes (l=r). Verified byte-for-byte
    against the C reference pk by the caller."""
    pkseed, skseed = seed48[:16], seed48[16:]
    Sps = V.powers(V.official_S(p.l), p.l)          # <-- was official_S(4),4
    raw = hashlib.shake_256(skseed).digest(2*p.o*p.v*p.l)
    vals = []; bound = (256//Q)*Q
    for b in raw:
        if b < bound:
            vals.append(b % Q)
            if len(vals) == p.o*p.v*p.l: break
    T12 = np.zeros((p.v*p.l, p.o*p.l), dtype=np.int64)
    for i in range(p.v):
        for j in range(p.o):
            off = (i*p.o+j)*p.l
            T12[i*p.l:(i+1)*p.l, j*p.l:(j+1)*p.l] = V.gen_fqs(vals[off:off+p.l], Sps)
    nelems = p.m1*(p.v*p.l*(p.l+1)//2 + (p.v*(p.v-1)//2 + p.v*p.o)*p.l*p.l)
    data = np.frombuffer(V.snova_xof(pkseed, nelems), dtype=np.uint8).astype(np.int64) % Q; z = 0
    P = []; P22 = []
    for _ in range(p.m1):
        P11 = np.zeros((p.v*p.l, p.v*p.l), dtype=np.int64)
        P12 = np.zeros((p.v*p.l, p.o*p.l), dtype=np.int64)
        for ni in range(p.v):
            for i in range(p.l):
                for j in range(i, p.l):
                    x = int(data[z]); z += 1
                    P11[ni*p.l+i, ni*p.l+j] = x; P11[ni*p.l+j, ni*p.l+i] = x
            for nj in range(ni+1, p.v):
                for i in range(p.l):
                    for j in range(p.l):
                        x = int(data[z]); z += 1
                        P11[ni*p.l+i, nj*p.l+j] = x; P11[nj*p.l+j, ni*p.l+i] = x
            for nj in range(p.o):
                for i in range(p.l):
                    for j in range(p.l):
                        x = int(data[z]); z += 1
                        P12[ni*p.l+i, nj*p.l+j] = x
        P21 = P12.T.copy()
        p22 = -(T12.T@((P11@T12+P12) % Q) + P21@T12) % Q
        P22.append(p22); P.append(np.block([[P11, P12], [P21, p22]]) % Q)
    assert z == nelems
    arr = []
    for A in P22:
        for ni in range(p.o):
            for i in range(p.l):
                for j in range(i, p.l): arr.append(int(A[ni*p.l+i, ni*p.l+j]))
                for nj in range(ni+1, p.o):
                    for j in range(p.l): arr.append(int(A[ni*p.l+i, nj*p.l+j]))
    out = bytearray(); idx = 0
    while idx < len(arr):
        take = min(15, len(arr)-idx); val = sum(arr[idx+i]*Q**i for i in range(take)); idx += 15
        for _ in range(8): out.append(val % 256); val //= 256
    pk = pkseed+bytes(out[:math.ceil(8*len(arr)/15)])
    return pk, np.asarray(P, dtype=np.int64)


def pick_rho(p, rng):
    """Generic public relation of length r giving full-rank E (=K)."""
    base = np.array([1, 8, 9, 14, 3, 5, 11, 2, 7, 13], dtype=np.int64)
    for attempt in range(20):
        rho = base[:p.r].copy() if attempt == 0 else rng.integers(1, Q, size=p.r, dtype=np.int64)
        E, labels = V.build_E(p, V.reconstruct_abq(p), rho)
        if V.rank_mod(E) == p.unordered:
            return rho % Q
    raise RuntimeError("no full-rank rho found")


def build_residual(p, kat_path: Path, seed: int):
    kat = V.parse_kat(kat_path)
    seed48 = bytes.fromhex(kat['sk']); expected = bytes.fromhex(kat['pk'])
    pk, P = kat_public_key_general(seed48, p)
    if pk != expected:
        raise AssertionError(f"pk MISMATCH for {p.name}: reconstruction != C reference "
                             f"({len(pk)} vs {len(expected)} bytes)")
    abq = V.reconstruct_abq(p)
    rng = np.random.default_rng(seed)
    rho = pick_rho(p, rng)
    E, labels = V.build_E(p, abq, rho); er = V.rank_mod(E)
    assert er == p.unordered, f"rank(E)={er} != K={p.unordered}"
    H = V.nullspace_mod(E.T)
    Voff, fmt = V.safe_offsets(p, rho, rng)
    f0 = V.direct_output(p, abq, P, Voff)
    Lmat = np.zeros((p.outputs, p.variables), dtype=np.int64)
    for j in range(p.variables):
        e = np.zeros(p.variables, dtype=np.int64); e[j] = 1
        Lmat[:, j] = (V.direct_output(p, abq, P, V.relation_U(p, e, rho, Voff))
                      - f0 - E @ V.coords(p, P, e, labels)) % Q
    xstar = rng.integers(0, Q, size=p.variables, dtype=np.int64)
    target = V.direct_output(p, abq, P, V.relation_U(p, xstar, rho, Voff))
    C = H @ Lmat % Q; b = H @ (target - f0) % Q
    x0, T, free, piv = V.affine_solve(C, b)
    zstar = xstar[free]
    assert np.array_equal((x0 + T @ zstar) % Q, xstar)
    rows = V.rref_mod(E.T)[1][:er]
    Sps = V.powers(V.official_S(p.l), p.l)
    KS = [V.kronS(A, p.n) for A in Sps]
    Mlist = [(KS[a].T @ P[pp] @ KS[bl]) % Q for (pp, a, bl) in labels]
    polys = []
    for r in rows:
        Gr = np.zeros((p.variables, p.variables), dtype=np.int64)
        Erow = E[r]
        for j in range(len(Mlist)):
            c = int(Erow[j]) % Q
            if c: Gr = (Gr + c*Mlist[j]) % Q
        A = (T.T @ Gr @ T) % Q
        lin_x = Lmat[r].astype(np.int64)
        lin_z = ((x0 @ (Gr + Gr.T) % Q) @ T + lin_x @ T) % Q
        const = (int(x0 @ Gr @ x0 % Q) + int(lin_x @ x0 % Q)
                 + int(f0[r]) - int(target[r])) % Q
        polys.append((A % Q, lin_z % Q, const % Q))
    return dict(p=p, free=free, x0=x0, T=T, zstar=zstar, rows=rows, polys=polys,
                E=E, Lmat=Lmat, f0=f0, target=target, abq=abq, P=P, rho=rho,
                Voff=Voff, labels=labels, V=V, kat_match=True, er=er,
                left_kernel=int(H.shape[0]), lin_rank=len(piv),
                residual_vars=T.shape[1])


def density(polys, nvar):
    maxq = nvar*(nvar+1)//2
    dens = [sum(1 for i in range(nvar) for j in range(i, nvar)
                if ((int(A[i, i]) % Q) if i == j else ((int(A[i, j])+int(A[j, i])) % Q)))/maxq
            for (A, _, _) in polys]
    return float(np.mean(dens))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--shape', required=True, choices=list(SHAPES))
    ap.add_argument('--seed', type=int, default=20260721)
    ap.add_argument('--outdir', default=str(ROOT/'experiments'/'systems'))
    args = ap.parse_args()
    sh = SHAPES[args.shape]
    p = V.PARAMS[sh['idx']]
    kat_path = SNAP/sh['kat']
    print(f"[*] shape {args.shape} {p.name} (v,o,l,r)=({p.v},{p.o},{p.l},{p.r}) K={p.unordered} kind={sh['kind']}", flush=True)
    if sh['kind'] == 'supplementary':
        print(f"[!] SUPPLEMENTARY core: the paper's l=2 gate-cost core is a Hashimoto "
              f"{sh['hashimoto']} produced by a change of basis, NOT emitted here. This "
              f"square-specialization core is a valid alternative attack path on the same "
              f"official key, run only as a structural cross-check.", flush=True)
    data = build_residual(p, kat_path, args.seed)
    print(f"[*] official pk match: byte-for-byte OK; residual {data['er']} quadratics / {data['residual_vars']} vars", flush=True)
    assert EM.verify_polys(data), "EMITTED POLYNOMIALS DO NOT MATCH REFERENCE VERIFIER"
    print("    verifier net PASSED (200 random points, exact F_19)", flush=True)
    assert EM.planted_check(data), "planted root not a root"
    print(f"    planted root satisfies all {data['er']} residual quadratics", flush=True)
    outdir = Path(args.outdir); outdir.mkdir(parents=True, exist_ok=True)
    tag = args.shape if sh['kind'] == 'paper-core' else f"{args.shape}_sqspec"
    EM.to_msolve(data['polys'], data['residual_vars'], outdir/f"{tag}_residual_{data['er']}in{data['residual_vars']}.ms")
    newpolys, keep, zc = EM.specialize(data, sh['core_n'], seed=args.seed)
    EM.to_msolve(newpolys, sh['core_n'], outdir/f"{tag}_core_{data['er']}in{sh['core_n']}.ms")
    EM.to_magma(newpolys, sh['core_n'], outdir/f"{tag}_core_{data['er']}in{sh['core_n']}.mag")
    meta = dict(shape=args.shape, params=[p.v, p.o, p.l, p.r], official_key=True,
                kind=sh['kind'],
                method=('square specialization (paper attack core)' if sh['kind'] == 'paper-core'
                        else 'square specialization (SUPPLEMENTARY structural check; '
                             'NOT the paper l=2 Hashimoto gate-cost core)'),
                pk_bytes=len(data['P']), residual=f"{data['er']}/{data['residual_vars']}",
                core=f"{data['er']}/{sh['core_n']}",
                hashimoto_gate_core=sh.get('hashimoto'),
                planted_core_solution=[int(x) for x in zc], kept_coords=keep,
                quad_support_density_core=density(newpolys, sh['core_n']),
                quad_support_density_residual=density(data['polys'], data['residual_vars']))
    (outdir/f"{tag}_core_meta.json").write_text(json.dumps(meta, indent=2)+"\n")
    print(f"[*] wrote {tag} core {data['er']}/{sh['core_n']} (density {meta['quad_support_density_core']:.4f})", flush=True)


if __name__ == '__main__':
    main()
